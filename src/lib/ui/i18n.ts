const tables: Record<AppLocale, Dict> = { zh, en };

export type MessageKey = keyof typeof zh;

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let text = tables[appLocale.current][key] ?? zh[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function localizeNetworkLabel(label: string): string {
  if (label === "以太网") return t("ethernet");
  if (label === "本机") return t("thisMac");
  return label;
}

export function localizeDeviceName(name: string): string {
  if (name === "Android 设备") return t("androidDevice");
  if (name === "Windows 电脑") return t("windowsPc");
  if (name === "Linux 设备") return t("linuxDevice");
  if (name === "未知设备") return t("deviceUnknown");
  if (name === "浏览器") return t("browser");
  return name;
}

export function localizeSiteName(name: string): string {
  if (name === "网站") return t("siteFallback");
  if (name === "未命名网站") return t("unnamedSite");
  return name;
}

export function localizeAssetsMode(value: string): string {
  if (value === "目录直读" || value === "static") return t("staticFiles");
  return value;
}

export function localizeUpdated(value: string): string {
  if (!value || value === "刚刚") return t("justNow");
  return value;
}

const ERROR_KEYS: Record<string, MessageKey> = {
  已取消: "cancelled",
  请选择网站目录: "errChooseFolder",
  "未找到所选 HTML 文件": "errHtmlNotFound",
  "未找到 HTML 入口": "errNoHtmlEntry",
  请先选择网站: "errChooseSiteFirst",
  入口不存在: "errEntryMissing",
  未在共享: "errNotSharing",
  访问码已关闭: "errCodeOff",
  未找到入口: "noEntry",
  没有可用的局域网地址: "errNoLan",
  当前没有进行中的分享: "errNoActiveShare",
  "这是 VibeShare 自己的端口，转发会造成死循环": "errSelfPort",
  这个网卡没有可用地址: "errNoAdapter",
  无法解析目录: "errCannotParseDir",
  无法保存设备黑名单: "errSaveBlacklist",
  无法监听端口: "errListenPort",
};

export function localizeError(error: unknown): string {
  const text = String(error).replace(/^Error:\s*/, "");
  const mapped = ERROR_KEYS[text];
  if (mapped) return t(mapped);
  const timeout = text.match(/^连接 127\.0\.0\.1:(\d+) 超时$/);
  if (timeout) return t("errConnectTimeout", { port: timeout[1] });
  if (text.startsWith("无法保存设备黑名单")) return t("errSaveBlacklist");
  return text;
}
